#!/usr/bin/env bash
#
# setup/ndk-shim.sh — prepare a shadow NDK toolchain for ndk-build on this host.
#
# WHY
#   The Android NDK ships an x86_64-only prebuilt toolchain. This machine is
#   aarch64, and the NDK copy here has its binaries replaced with the system
#   LLVM 18. Two things break:
#
#     1. `-lgcc` is added to every link, but the NDK ships no libgcc.a for
#        API < 24 (this project targets minSdk 21). In a working NDK build the
#        flag is satisfied by the compiler runtime, so the linker wrapper
#        substitutes the matching libunwind.a + libclang_rt.builtins archive.
#     2. `--sysroot PATH` (two tokens) is not rewritten for the Android target
#        by the system clang driver, so `crtbegin_so.o` is not found. Only the
#        single-token `--sysroot=PATH` form works.
#
# WHAT IT DOES
#   Builds a shadow NDK tree at $NDK_SHIM_ROOT whose `toolchains/llvm/prebuilt/
#   <host>` mirrors the real one, except:
#     - `bin/clang` and `bin/clang++` are wrappers that normalize `--sysroot`
#       and pass `-fuse-ld=<wrapper ld.lld>`;
#     - `bin/ld.lld` (and `ld`) are wrappers that drop `-lgcc` and delegate to
#       the real linker.
#   Everything else (sysroot, libs, includes) is symlinked, so the tree is
#   otherwise identical. The installed NDK is never modified.
#
# USAGE
#   eval "$(./setup/ndk-shim.sh --env)"    # create the tree and export GNUMAKE
#   ./gradlew :app:assembleDebug
#
#   ./setup/ndk-shim.sh                    # just create it, print its path
#   NDK_SHIM_ROOT=/tmp/... ./setup/ndk-shim.sh
#
# Only needed on hosts whose architecture does not match the NDK's prebuilt
# toolchain (i.e. aarch64 here). On x86_64 the stock NDK works unchanged.

set -eu

: "${ANDROID_NDK_HOME:?ANDROID_NDK_HOME must be set to the NDK to shadow}"

REAL_NDK="$ANDROID_NDK_HOME"
HOST_TAG="linux-x86_64"
REAL_PREBUILT="$REAL_NDK/toolchains/llvm/prebuilt/$HOST_TAG"
SYSROOT="$REAL_PREBUILT/sysroot"
REAL_LD="$REAL_PREBUILT/bin/ld.lld"

[ -d "$REAL_PREBUILT" ] || { echo "error: no prebuilt dir at $REAL_PREBUILT" >&2; exit 1; }
[ -d "$SYSROOT" ] || { echo "error: no sysroot at $SYSROOT" >&2; exit 1; }
[ -e "$REAL_LD" ] || { echo "error: no linker at $REAL_LD" >&2; exit 1; }

# Keep the shadow tree outside the real NDK: never modify the installed NDK.
SHADOW_ROOT="${NDK_SHIM_ROOT:-/tmp/opencode/ndk-shadow}"
SHADOW_HOST="$SHADOW_ROOT/toolchains/llvm/prebuilt/$HOST_TAG"

rm -rf "$SHADOW_ROOT"
mkdir -p "$SHADOW_HOST/bin"

# Top-level NDK entries (build/, sources/, ...) so the shadow tree is usable as
# a drop-in NDK.
for entry in "$REAL_NDK"/*; do
    name=$(basename "$entry")
    case "$name" in
        toolchains|ndk-build) continue ;;
    esac
    ln -s "$entry" "$SHADOW_ROOT/$name"
done

# The stock `ndk-build` forwards to `$DIR/build/ndk-build`, which derives
# ANDROID_NDK_ROOT from its own path. Because `build/` is a symlink here, that
# would resolve back to the real NDK and silently bypass the wrappers. This
# replacement pins NDK_ROOT to the shadow tree instead.
cat > "$SHADOW_ROOT/ndk-build" <<EOF
#!/usr/bin/env bash
# Generated by setup/ndk-shim.sh — runs the stock ndk-build against the shadow NDK.
set -eu
# The NDK's bundled python3 is an x86-64 binary. Point ndk-build at the host's
# own interpreter instead, which is what it falls back to when none is found.
exec "$REAL_NDK/build/ndk-build" NDK_ROOT="$SHADOW_ROOT" \\
    NDK_HOST_PYTHON="\${NDK_HOST_PYTHON:-\$(command -v python3)}" "\$@"
EOF
chmod +x "$SHADOW_ROOT/ndk-build"

# Mirror the prebuilt tree, except `bin`, which is rebuilt below.
for entry in "$REAL_PREBUILT"/*; do
    name=$(basename "$entry")
    [ "$name" = "bin" ] && continue
    ln -s "$entry" "$SHADOW_HOST/$name"
done

# Mirror the toolchain binaries, except the ones replaced by wrappers.
for entry in "$REAL_PREBUILT/bin"/*; do
    name=$(basename "$entry")
    case "$name" in
        clang|clang++|ld.lld|ld) continue ;;
    esac
    ln -s "$entry" "$SHADOW_HOST/bin/$name"
done

# --- ld.lld wrapper: translate -lgcc, delegate to the real linker. ----------
#
# `-lgcc` is not GCC here: in a normal NDK build it resolves to the NDK's
# compiler runtime (libunwind.a + libclang_rt.builtins). On this host the
# driver cannot find it, so the archives are substituted explicitly. Without
# them the C++ libraries fail to link (`_Unwind_Resume`, `__aarch64_ldadd*`).
cat > "$SHADOW_HOST/bin/ld.lld" <<EOF
#!/usr/bin/env bash
# Generated by setup/ndk-shim.sh — see that file for why this exists.
set -eu

CRT_LIB="$REAL_PREBUILT/lib/clang/18/lib/linux"
REAL_LD="$REAL_LD"

# Pick the runtime archives for the target ABI. ld.lld receives the emulation
# as two tokens (\`-m aarch64linux\`), so match on the emulation name itself.
arch=""
for a in "\$@"; do
    case "\$a" in
        aarch64linux) arch=aarch64 ;;
        armelf_linux_eabi) arch=arm ;;
        elf_x86_64) arch=x86_64 ;;
        elf_i386) arch=i386 ;;
    esac
done

args=()
for a in "\$@"; do
    if [ "\$a" = "-lgcc" ] && [ -n "\$arch" ]; then
        args+=("\$CRT_LIB/\$arch/libunwind.a" "\$CRT_LIB/libclang_rt.builtins-\$arch-android.a")
    else
        args+=("\$a")
    fi
done
exec "\$REAL_LD" "\${args[@]}"
EOF
chmod +x "$SHADOW_HOST/bin/ld.lld"
ln -s "ld.lld" "$SHADOW_HOST/bin/ld"

# --- clang / clang++ wrapper: normalize --sysroot, force the shim linker. ---
write_clang_wrapper() {
    local name="$1" real="$2"
    cat > "$SHADOW_HOST/bin/$name" <<EOF
#!/usr/bin/env bash
# Generated by setup/ndk-shim.sh — see that file for why this exists.
#  - forces \`--sysroot=<dir>\` so crtbegin_so.o resolves
#  - forces the shim linker so its \`-lgcc\` is translated
set -eu
args=()
skip=0
for a in "\$@"; do
    if [ "\$skip" = "1" ]; then skip=0; continue; fi
    case "\$a" in
        --sysroot) skip=1; continue ;;
        --sysroot=*|-fuse-ld=*) continue ;;
        *) args+=("\$a") ;;
    esac
done
exec "$real" --sysroot="$SYSROOT" -fuse-ld="$SHADOW_HOST/bin/ld.lld" "\${args[@]}"
EOF
    chmod +x "$SHADOW_HOST/bin/$name"
}

write_clang_wrapper clang   "$REAL_PREBUILT/bin/clang"
write_clang_wrapper clang++ "$REAL_PREBUILT/bin/clang++"

# The per-API driver scripts call ../../bin/clang, which resolves through this
# shared bin dir, so they pick up the wrappers automatically.

# --- make wrapper ------------------------------------------------------------
# AGP resolves the NDK from `ndkVersion` against the SDK and ignores
# `android.ndkPath`, so the shadow tree cannot be selected at the Gradle level.
# It can be injected one level lower: `ndk-build` honours a `GNUMAKE` environment
# variable, and a make command-line assignment beats the `NDK_ROOT :=` that
# build-local.mk derives from its own path.
MAKE_DIR="$SHADOW_ROOT/host-make"
mkdir -p "$MAKE_DIR"
cat > "$MAKE_DIR/make" <<EOF
#!/usr/bin/env bash
# Generated by setup/ndk-shim.sh — runs make against the shadow NDK tree.
set -eu
exec "$(command -v make)" NDK_ROOT="$SHADOW_ROOT" \\
    NDK_HOST_PYTHON="\${NDK_HOST_PYTHON:-\$(command -v python3)}" "\$@"
EOF
chmod +x "$MAKE_DIR/make"

if [ "${1:-}" = "--env" ]; then
    # Print shell assignments for the caller to eval.
    echo "export GNUMAKE=\"$MAKE_DIR/make\""
else
    echo "$SHADOW_ROOT"
fi

